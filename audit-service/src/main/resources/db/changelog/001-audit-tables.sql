CREATE SEQUENCE AUDIT_EVENT_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;

CREATE TABLE AUDIT_EVENT (
    ID             NUMBER(19)         NOT NULL,
    EVENT_ID       VARCHAR2(36 CHAR)  NOT NULL,
    TOPIC          VARCHAR2(100 CHAR) NOT NULL,
    EVENT_TYPE     VARCHAR2(100 CHAR) NOT NULL,
    SOURCE_SERVICE VARCHAR2(60 CHAR),
    ACCOUNT_NO     VARCHAR2(34 CHAR),
    ACTOR          VARCHAR2(254 CHAR) NOT NULL,
    CORRELATION_ID VARCHAR2(64 CHAR),
    PAYLOAD        CLOB,
    OCCURRED_AT    TIMESTAMP WITH TIME ZONE NOT NULL,
    RECORDED_AT    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AUDIT_EVENT PRIMARY KEY (ID),
    CONSTRAINT UQ_AUDIT_EVENT_ID UNIQUE (EVENT_ID)
);
CREATE INDEX IX_AUDIT_ACCOUNT ON AUDIT_EVENT (ACCOUNT_NO, OCCURRED_AT);
CREATE INDEX IX_AUDIT_CORRELATION ON AUDIT_EVENT (CORRELATION_ID);
CREATE INDEX IX_AUDIT_OCCURRED ON AUDIT_EVENT (OCCURRED_AT);

--changeset bank:aud-002-insert-only splitStatements:false endDelimiter:/
CREATE OR REPLACE TRIGGER TRG_AUDIT_EVENT_IMMUTABLE
BEFORE UPDATE OR DELETE ON AUDIT_EVENT
BEGIN
    RAISE_APPLICATION_ERROR(-20001, 'AUDIT_EVENT is insert-only');
END;
