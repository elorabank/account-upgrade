CREATE SEQUENCE OUTBOX_EVENT_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;

CREATE TABLE OUTBOX_EVENT (
    ID             NUMBER(19)                 NOT NULL,
    EVENT_ID       VARCHAR2(36 CHAR)          NOT NULL,
    TOPIC          VARCHAR2(100 CHAR)         NOT NULL,
    MSG_KEY        VARCHAR2(100 CHAR),
    EVENT_TYPE     VARCHAR2(100 CHAR)         NOT NULL,
    AGGREGATE_ID   VARCHAR2(64 CHAR),
    CORRELATION_ID VARCHAR2(64 CHAR),
    PAYLOAD        CLOB                       NOT NULL,
    STATUS         VARCHAR2(12 CHAR)          DEFAULT 'NEW' NOT NULL,
    CREATED_AT     TIMESTAMP WITH TIME ZONE   DEFAULT SYSTIMESTAMP NOT NULL,
    PUBLISHED_AT   TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_OUTBOX_EVENT PRIMARY KEY (ID),
    CONSTRAINT UQ_OUTBOX_EVENT_ID UNIQUE (EVENT_ID),
    CONSTRAINT CK_OUTBOX_STATUS CHECK (STATUS IN ('NEW', 'PUBLISHED'))
);

CREATE INDEX IX_OUTBOX_STATUS_ID ON OUTBOX_EVENT (STATUS, ID);
