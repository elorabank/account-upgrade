-- Runs once, on first start of the local Oracle container.
-- One schema per service. Local passwords only; real environments use Vault.
ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE USER ing_owner IDENTIFIED BY ing_local_pw QUOTA UNLIMITED ON users;
CREATE USER upg_owner IDENTIFIED BY upg_local_pw QUOTA UNLIMITED ON users;
CREATE USER com_owner IDENTIFIED BY com_local_pw QUOTA UNLIMITED ON users;
CREATE USER aud_owner IDENTIFIED BY aud_local_pw QUOTA UNLIMITED ON users;

GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW, CREATE TRIGGER TO ing_owner;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW, CREATE TRIGGER TO upg_owner;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW, CREATE TRIGGER TO com_owner;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW, CREATE TRIGGER TO aud_owner;
