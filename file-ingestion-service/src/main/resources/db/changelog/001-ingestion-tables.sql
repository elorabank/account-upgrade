CREATE SEQUENCE FILE_INGESTION_LOG_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE ACCOUNT_STAGING_SEQ    START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE INGESTION_ERROR_SEQ    START WITH 1 INCREMENT BY 50 NOCACHE;

CREATE TABLE FILE_INGESTION_LOG (
    ID                 NUMBER(19)         NOT NULL,
    FILE_NAME          VARCHAR2(255 CHAR) NOT NULL,
    CHECKSUM           VARCHAR2(64 CHAR)  NOT NULL,
    BUSINESS_DATE      DATE               NOT NULL,
    STATUS             VARCHAR2(20 CHAR)  NOT NULL,
    TOTAL_ROWS         NUMBER(10),
    LOADED_ROWS        NUMBER(10),
    REJECTED_ROWS      NUMBER(10),
    LAST_COMMITTED_ROW NUMBER(10)         DEFAULT 0 NOT NULL,
    ERROR_MESSAGE      VARCHAR2(2000 CHAR),
    STARTED_AT         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    COMPLETED_AT       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_FILE_INGESTION_LOG PRIMARY KEY (ID),
    CONSTRAINT UQ_FILE_CHECKSUM UNIQUE (CHECKSUM),
    CONSTRAINT CK_FILE_STATUS CHECK (STATUS IN ('RUNNING', 'COMPLETED', 'FAILED'))
);

-- NOTE: columns follow the draft Excel layout. Adjust once the business confirms the template.
CREATE TABLE ACCOUNT_STAGING (
    ID            NUMBER(19)         NOT NULL,
    FILE_ID       NUMBER(19)         NOT NULL,
    ROW_NO        NUMBER(10)         NOT NULL,
    ACCOUNT_NO    VARCHAR2(34 CHAR)  NOT NULL,
    CUSTOMER_ID   VARCHAR2(36 CHAR)  NOT NULL,
    CUSTOMER_NAME VARCHAR2(200 CHAR) NOT NULL,
    EMAIL         VARCHAR2(254 CHAR) NOT NULL,
    CURRENT_TYPE  VARCHAR2(30 CHAR)  NOT NULL,
    BALANCE       NUMBER(18,2),
    KYC_STATUS    VARCHAR2(20 CHAR),
    RAW_ROW_JSON  CLOB,
    CONSTRAINT PK_ACCOUNT_STAGING PRIMARY KEY (ID),
    CONSTRAINT FK_STAGING_FILE FOREIGN KEY (FILE_ID) REFERENCES FILE_INGESTION_LOG (ID),
    CONSTRAINT UQ_STAGING_FILE_ROW UNIQUE (FILE_ID, ROW_NO)
);
CREATE INDEX IX_STAGING_ACCOUNT ON ACCOUNT_STAGING (ACCOUNT_NO);

CREATE TABLE INGESTION_ERROR (
    ID            NUMBER(19)          NOT NULL,
    FILE_ID       NUMBER(19)          NOT NULL,
    ROW_NO        NUMBER(10)          NOT NULL,
    ERROR_MESSAGE VARCHAR2(2000 CHAR) NOT NULL,
    RAW_ROW_JSON  CLOB,
    CREATED_AT    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_INGESTION_ERROR PRIMARY KEY (ID),
    CONSTRAINT FK_ERROR_FILE FOREIGN KEY (FILE_ID) REFERENCES FILE_INGESTION_LOG (ID)
);
CREATE INDEX IX_ERROR_FILE ON INGESTION_ERROR (FILE_ID);
