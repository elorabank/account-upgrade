CREATE SEQUENCE LETTER_TEMPLATE_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;
CREATE SEQUENCE WELCOME_LETTER_SEQ  START WITH 1 INCREMENT BY 50 NOCACHE;

-- HTML templates per account type, versioned; the highest ACTIVE version is used
CREATE TABLE LETTER_TEMPLATE (
    ID             NUMBER(19)         NOT NULL,
    TEMPLATE_CODE  VARCHAR2(60 CHAR)  NOT NULL,
    ACCOUNT_TYPE   VARCHAR2(30 CHAR)  NOT NULL,
    VERSION_NO     NUMBER(5)          NOT NULL,
    SUBJECT        VARCHAR2(300 CHAR) NOT NULL,
    BODY_HTML      CLOB               NOT NULL,
    ACTIVE         NUMBER(1)          DEFAULT 0 NOT NULL,
    CREATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_LETTER_TEMPLATE PRIMARY KEY (ID),
    CONSTRAINT UQ_TEMPLATE_VERSION UNIQUE (TEMPLATE_CODE, VERSION_NO),
    CONSTRAINT CK_TEMPLATE_ACTIVE CHECK (ACTIVE IN (0, 1))
);
CREATE INDEX IX_TEMPLATE_TYPE_ACTIVE ON LETTER_TEMPLATE (ACCOUNT_TYPE, ACTIVE);

-- One row per upgraded account: the letter, which is also the email body, and how its delivery went
CREATE TABLE WELCOME_LETTER (
    ID             NUMBER(19)          NOT NULL,
    ACCOUNT_NO     VARCHAR2(34 CHAR)   NOT NULL,
    CUSTOMER_ID    VARCHAR2(36 CHAR)   NOT NULL,
    RECIPIENT      VARCHAR2(254 CHAR)  NOT NULL,
    TEMPLATE_ID    NUMBER(19)          NOT NULL,
    SUBJECT        VARCHAR2(300 CHAR)  NOT NULL,
    HTML_BODY      CLOB                NOT NULL,
    STATUS         VARCHAR2(20 CHAR)   DEFAULT 'PENDING' NOT NULL,
    ATTEMPTS       NUMBER(3)           DEFAULT 0 NOT NULL,
    ERROR_MESSAGE  VARCHAR2(2000 CHAR),
    CORRELATION_ID VARCHAR2(64 CHAR),
    GENERATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    SENT_AT        TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_WELCOME_LETTER PRIMARY KEY (ID),
    CONSTRAINT FK_LETTER_TEMPLATE FOREIGN KEY (TEMPLATE_ID) REFERENCES LETTER_TEMPLATE (ID),
    CONSTRAINT CK_LETTER_STATUS CHECK (STATUS IN ('PENDING', 'SENT', 'FAILED'))
);
CREATE INDEX IX_LETTER_ACCOUNT ON WELCOME_LETTER (ACCOUNT_NO);
CREATE INDEX IX_LETTER_STATUS ON WELCOME_LETTER (STATUS);
