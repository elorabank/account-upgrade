CREATE SEQUENCE UPGRADE_REQUEST_SEQ START WITH 1 INCREMENT BY 50 NOCACHE;

CREATE TABLE UPGRADE_REQUEST (
    ID             NUMBER(19)         NOT NULL,
    ACCOUNT_NO     VARCHAR2(34 CHAR)  NOT NULL,
    CUSTOMER_ID    VARCHAR2(36 CHAR)  NOT NULL,
    CUSTOMER_NAME  VARCHAR2(200 CHAR) NOT NULL,
    EMAIL          VARCHAR2(254 CHAR) NOT NULL,
    CURRENT_TYPE   VARCHAR2(30 CHAR)  NOT NULL,
    TARGET_TYPE    VARCHAR2(30 CHAR),
    STATUS         VARCHAR2(20 CHAR)  DEFAULT 'PENDING' NOT NULL,
    ATTEMPT_COUNT  NUMBER(3)          DEFAULT 0 NOT NULL,
    REASON         VARCHAR2(1000 CHAR),
    BUSINESS_DATE  DATE               NOT NULL,
    SOURCE_FILE_ID NUMBER(19),
    RUN_ID         VARCHAR2(36 CHAR),
    VERSION        NUMBER(19)         DEFAULT 0 NOT NULL,
    CREATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_UPGRADE_REQUEST PRIMARY KEY (ID),
    CONSTRAINT UQ_UPGRADE_ACCOUNT_DATE UNIQUE (ACCOUNT_NO, BUSINESS_DATE),
    CONSTRAINT CK_UPGRADE_STATUS CHECK (STATUS IN ('PENDING', 'IN_PROGRESS', 'UPGRADED', 'REJECTED', 'FAILED'))
);
CREATE INDEX IX_UPGRADE_STATUS_DATE ON UPGRADE_REQUEST (STATUS, BUSINESS_DATE);
CREATE INDEX IX_UPGRADE_RUN ON UPGRADE_REQUEST (RUN_ID);
